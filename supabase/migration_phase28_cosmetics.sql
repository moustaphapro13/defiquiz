begin;
alter table public.profiles add column if not exists banner text not null default '';
alter table public.profiles add column if not exists bubble text not null default '';

create or replace function public.set_cosmetics(p_banner text, p_bubble text) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare me uuid := auth.uid();
begin
  perform public.assert_active(me);
  if coalesce(p_banner, '') <> '' and not exists (select 1 from public.inventory where user_id = me and item = 'banner:' || p_banner) then
    raise exception 'cette bannière n''est pas encore à toi';
  end if;
  if coalesce(p_bubble, '') <> '' and not exists (select 1 from public.inventory where user_id = me and item = 'bubble:' || p_bubble) then
    raise exception 'cette bulle n''est pas encore à toi';
  end if;
  update public.profiles set banner = coalesce(p_banner, ''), bubble = coalesce(p_bubble, '') where id = me;
end $$;
grant execute on function public.set_cosmetics(text, text) to authenticated;

